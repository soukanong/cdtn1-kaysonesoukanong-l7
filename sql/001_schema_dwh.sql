-- Kho dữ liệu (schema dwh): 4 dimension + 2 fact theo Hình 4.2 của BT1.
-- Mọi câu lệnh đều IDEMPOTENT (IF NOT EXISTS / ON CONFLICT) nên chạy lại không lỗi.
-- Không dùng dấu chấm phẩy trong chú thích: db.apply_schema tách câu lệnh theo dấu chấm phẩy.

CREATE SCHEMA IF NOT EXISTS dwh;
CREATE SCHEMA IF NOT EXISTS stg;
CREATE SCHEMA IF NOT EXISTS core;

-- dim_date: SCD loại 0
CREATE TABLE IF NOT EXISTS dwh.dim_date (
    date_key    INT PRIMARY KEY,
    full_date   DATE,
    month_no    SMALLINT,
    quarter_no  SMALLINT,
    year_no     SMALLINT
);

-- dim_run: SCD loại 0
CREATE TABLE IF NOT EXISTS dwh.dim_run (
    run_key          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at       TIMESTAMP,
    finished_at      TIMESTAMP,
    source_file      VARCHAR(100),
    source_row_count INT,
    status           VARCHAR(10) CHECK (status IN ('SUCCESS', 'FAILED', 'RUNNING'))
);

-- dim_dq_rule: SCD loại 2 cho threshold_pct (mỗi lần đổi ngưỡng thêm một dòng)
CREATE TABLE IF NOT EXISTS dwh.dim_dq_rule (
    rule_key           SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_code          VARCHAR(10),
    rule_name          VARCHAR(120),
    quality_dimension  VARCHAR(20),
    column_name        VARCHAR(40),
    threshold_pct      NUMERIC(5,2),
    is_active          BOOLEAN DEFAULT TRUE,
    valid_from         DATE,
    valid_to           DATE NULL,
    is_current         BOOLEAN DEFAULT TRUE
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_dim_dq_rule_current
    ON dwh.dim_dq_rule (rule_code) WHERE is_current;

-- dim_store: SCD loại 1
CREATE TABLE IF NOT EXISTS dwh.dim_store (
    store_key   INT PRIMARY KEY,
    store_code  VARCHAR(20),
    store_name  VARCHAR(100),
    city        VARCHAR(50)
);

-- Dòng Unknown (khóa -1) cho mọi dimension (Mục 4.2.4)
INSERT INTO dwh.dim_date  (date_key, full_date, month_no, quarter_no, year_no)
    VALUES (-1, NULL, NULL, NULL, NULL) ON CONFLICT DO NOTHING;
INSERT INTO dwh.dim_run   (run_key, status)
    OVERRIDING SYSTEM VALUE VALUES (-1, 'FAILED') ON CONFLICT DO NOTHING;
INSERT INTO dwh.dim_dq_rule (rule_key, rule_code, rule_name, is_current)
    OVERRIDING SYSTEM VALUE VALUES (-1, 'UNKNOWN', 'Unknown', FALSE) ON CONFLICT DO NOTHING;
INSERT INTO dwh.dim_store (store_key, store_code, store_name, city)
    VALUES (-1, 'UNKNOWN', 'Unknown', NULL) ON CONFLICT DO NOTHING;

-- GRAIN: một dòng = kết quả đo MỘT quy tắc ở MỘT giai đoạn của MỘT cửa hàng trong MỘT đợt chạy
CREATE TABLE IF NOT EXISTS dwh.fact_dq_result (
    result_key        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_key          INT      NOT NULL REFERENCES dwh.dim_date (date_key),
    run_key           BIGINT   NOT NULL REFERENCES dwh.dim_run (run_key),
    rule_key          SMALLINT NOT NULL REFERENCES dwh.dim_dq_rule (rule_key),
    store_key         INT      NOT NULL REFERENCES dwh.dim_store (store_key),
    stage             VARCHAR(5) NOT NULL CHECK (stage IN ('RAW', 'CLEAN')),
    total_records     INT,
    failed_records    INT,
    pass_rate_pct     NUMERIC(5,2),
    is_threshold_met  BOOLEAN,
    UNIQUE (run_key, rule_key, stage, store_key)
);

-- GRAIN: một dòng = MỘT lần vi phạm MỘT quy tắc của MỘT hồ sơ thô trong MỘT đợt chạy
-- stg_id là dimension suy biến (không khóa ngoại), issue_detail không chứa số điện thoại đầy đủ
CREATE TABLE IF NOT EXISTS dwh.fact_dq_issue (
    issue_key     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_key      INT      NOT NULL REFERENCES dwh.dim_date (date_key),
    run_key       BIGINT   NOT NULL REFERENCES dwh.dim_run (run_key),
    rule_key      SMALLINT NOT NULL REFERENCES dwh.dim_dq_rule (rule_key),
    store_key     INT      NOT NULL REFERENCES dwh.dim_store (store_key),
    stg_id        BIGINT,
    dup_group_id  BIGINT NULL,
    issue_detail  VARCHAR(255)
);
