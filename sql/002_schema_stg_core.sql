-- Lớp stg (xóa và nạp lại mỗi đợt) và lớp core (giữ lại giữa các đợt, upsert theo số điện thoại)

-- hồ sơ thô nguyên trạng
CREATE TABLE IF NOT EXISTS stg.stg_customer (
    stg_id          BIGINT PRIMARY KEY,
    source_row_no   INT,
    record_id_raw   VARCHAR(100),
    full_name_raw   TEXT,
    phone_raw       TEXT,
    email_raw       TEXT,
    address_raw     TEXT,
    created_at_raw  TEXT,
    run_key         BIGINT
);

-- bảng trung gian: hồ sơ đã chuẩn hóa và đã khử trùng theo số điện thoại, chờ upsert vào core
CREATE TABLE IF NOT EXISTS stg.stg_customer_clean (
    source_row_no  INT PRIMARY KEY,
    full_name      VARCHAR(120),
    phone          VARCHAR(20),
    email          VARCHAR(120),
    address        VARCHAR(255),
    created_at     TIMESTAMP
);

-- nhóm nghi trùng tìm được ở đợt chạy này (tham chiếu bằng số điện thoại)
CREATE TABLE IF NOT EXISTS stg.stg_duplicate (
    group_id    BIGINT,
    phone       VARCHAR(20),
    match_rule  VARCHAR(20)
);

-- hồ sơ sạch (QT-13: không xóa vật lý, chỉ đánh dấu ngừng sử dụng)
CREATE TABLE IF NOT EXISTS core.customer_clean (
    customer_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR(120) NOT NULL,
    phone           VARCHAR(20)  NOT NULL UNIQUE CHECK (phone ~ '^0[0-9]{9}$'),
    email           VARCHAR(120),
    address         VARCHAR(255),
    store_key       INT NOT NULL DEFAULT -1 REFERENCES dwh.dim_store (store_key),
    created_at      TIMESTAMP,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    merged_into_id  BIGINT REFERENCES core.customer_clean (customer_id)
);

-- bản ghi bị loại, luôn kèm mã lý do (NFR6)
CREATE TABLE IF NOT EXISTS core.reject_customer (
    reject_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stg_id       BIGINT NOT NULL REFERENCES stg.stg_customer (stg_id),
    run_key      BIGINT NOT NULL,
    reason_code  VARCHAR(30) NOT NULL,
    reason_text  VARCHAR(255)
);

-- hồ sơ nghi trùng chờ xác nhận (BR-L7-04)
CREATE TABLE IF NOT EXISTS core.duplicate_review (
    review_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id     BIGINT NOT NULL,
    customer_id  BIGINT NOT NULL REFERENCES core.customer_clean (customer_id),
    match_rule   VARCHAR(20) CHECK (match_rule IN ('EMAIL', 'NAME_ADDR')),
    status       VARCHAR(10) NOT NULL DEFAULT 'PENDING'
                 CHECK (status IN ('PENDING', 'CONFIRMED', 'REJECTED')),
    reviewed_by  VARCHAR(50),
    reviewed_at  TIMESTAMP,
    UNIQUE (group_id, customer_id)
);

-- lịch sử gộp (BR-L7-05)
CREATE TABLE IF NOT EXISTS core.merge_log (
    merge_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id             BIGINT,
    primary_customer_id  BIGINT NOT NULL REFERENCES core.customer_clean (customer_id),
    merged_customer_id   BIGINT NOT NULL REFERENCES core.customer_clean (customer_id),
    merged_by            VARCHAR(50),
    merged_at            TIMESTAMP
);
